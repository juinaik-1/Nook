function normalizeQuery(query) {
  return String(query ?? '').trim().toLowerCase();
}

export function searchEmoji(query) {
  const q = normalizeQuery(query);
  if (!q) return ALL_EMOJI;
  return ALL_EMOJI.filter((item) => {
    const haystack = [item.name, ...(item.keywords || [])].join(' ').toLowerCase();
    return haystack.includes(q);
  });
}

// Load the recently-used list from localStorage. Returns an array of char strings.
export function loadRecent() {
  try {
    if (typeof window === 'undefined') return [];
    const raw = window.localStorage.getItem(RECENT_KEY);
    if (!raw) return [];
    const parsed = JSON.parse(raw);
    return Array.isArray(parsed) ? parsed.slice(0, RECENT_LIMIT) : [];
  } catch {
    return [];
  }
}

// Record a pick in the recently-used list. Keeps only the most recent N,
// deduplicated by character.
export function recordRecent(char) {
  try {
    if (typeof window === 'undefined') return loadRecent();
    const current = loadRecent().filter((item) => item !== char);
    const next = [char, ...current].slice(0, RECENT_LIMIT);
    window.localStorage.setItem(RECENT_KEY, JSON.stringify(next));
    return next;
  } catch {
    return loadRecent();
  }
}
